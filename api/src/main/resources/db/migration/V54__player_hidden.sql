-- Флаг «скрыт из публичных списков игроков».
--
-- Зачем: тестовые и служебные аккаунты светились в лидерборде и в пикере «добавить игрока»
-- (/api/players/rating). Веб прятал их случайно — фильтром «только откалиброванные», —
-- а мобильное приложение показывало всех. Отключать такие аккаунты (users.disabled) нельзя:
-- под ними заходят для тестов. Поэтому отдельный флаг: игрок работает как обычно,
-- но в публичные списки не попадает.
alter table players
    add column hidden boolean not null default false;

-- Задним числом скрываем уже удалённые аккаунты: клиенты отсекали их по префиксу имени
-- («Удалённый пользователь #…»), теперь это делает бэкенд и для старых сборок тоже.
update players set hidden = true where name like 'Удалённый %';
